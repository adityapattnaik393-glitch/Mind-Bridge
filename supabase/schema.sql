-- ============================================================================
-- MindBridge — Supabase schema
-- Run this ONCE in the Supabase SQL Editor (safe to re-run: everything is
-- "if not exists" / "or replace", so your existing `patients` table survives).
--
-- Workflow it supports:
--   caretaker creates an account (caretaker name, patient name, email,
--   password, language) -> signs in -> patient dashboard (games) and
--   caretaker dashboard (daily + overall progress) read the same rows.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. PATIENTS  (one row per account: the patient + their caretaker)
-- ---------------------------------------------------------------------------
create table if not exists public.patients (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  name text not null,
  age integer default 72,
  region text default 'Imphal, Manipur',
  preferred_language text default 'English',
  streak integer default 0,
  created_at timestamptz not null default now()
);

-- New columns for the caretaker-led signup flow (no-ops if already present).
alter table public.patients add column if not exists caretaker_name    text;
alter table public.patients add column if not exists caretaker_mobile  text;
alter table public.patients add column if not exists language_code     text default 'en';
alter table public.patients add column if not exists updated_at        timestamptz not null default now();

drop index if exists public.patients_caretaker_mobile_key;

create index if not exists patients_user_id_idx on public.patients (user_id);

-- ---------------------------------------------------------------------------
-- 2. GAME SCORES  (every completed cognitive session)
-- ---------------------------------------------------------------------------
create table if not exists public.game_scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  game_type text not null,
  score integer not null check (score between 0 and 100),
  attempts integer not null default 1,
  created_at timestamptz not null default now()
);

alter table public.game_scores add column if not exists category         text;
alter table public.game_scores add column if not exists duration_seconds integer default 180;
alter table public.game_scores add column if not exists difficulty       text default 'easy';

create index if not exists game_scores_user_created_idx
  on public.game_scores (user_id, created_at desc);

-- ---------------------------------------------------------------------------
-- 3. COGNITIVE ALERTS  (caregiver reminders + acknowledgements)
-- ---------------------------------------------------------------------------
create table if not exists public.cognitive_alerts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  alert_title text not null,
  status text not null default 'Acknowledged',
  created_at timestamptz not null default now()
);

alter table public.cognitive_alerts add column if not exists alert_body text;
alter table public.cognitive_alerts add column if not exists kind       text default 'reminder';

create index if not exists cognitive_alerts_user_created_idx
  on public.cognitive_alerts (user_id, created_at desc);

-- ---------------------------------------------------------------------------
-- 4. CARE GIFTS  (audio recordings and photos from the caretaker)
-- ---------------------------------------------------------------------------
create table if not exists public.care_gifts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  gift_type text not null check (gift_type in ('audio', 'photo')),
  title text not null,
  file_name text not null,
  mime_type text not null,
  media_data text not null,
  unlock_score integer not null default 90 check (unlock_score between 0 and 100),
  created_at timestamptz not null default now()
);

create index if not exists care_gifts_user_created_idx
  on public.care_gifts (user_id, created_at desc);

-- ---------------------------------------------------------------------------
