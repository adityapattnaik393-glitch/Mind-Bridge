  for insert with check (auth.uid() = user_id);

-- ---------------------------------------------------------------------------
-- 5. SIGNUP TRIGGER
--    Creates the patients row the instant an account is created, using the
--    metadata the server sends with signUp(). Runs as security definer so it
--    works even when the server only holds the anon key.
-- ---------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.patients (
    user_id, name, caretaker_name, caretaker_mobile,
    preferred_language, language_code, age, region
  )
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'patient_name', ''), 'Patient'),
    coalesce(nullif(new.raw_user_meta_data ->> 'caretaker_name', ''), 'Caretaker'),
    nullif(new.raw_user_meta_data ->> 'mobile', ''),
    coalesce(nullif(new.raw_user_meta_data ->> 'preferred_language', ''), 'English'),
    coalesce(nullif(new.raw_user_meta_data ->> 'language_code', ''), 'en'),
    coalesce((new.raw_user_meta_data ->> 'age')::int, 72),
    coalesce(nullif(new.raw_user_meta_data ->> 'region', ''), 'Imphal, Manipur')
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- ---------------------------------------------------------------------------
-- 6. DAILY PROGRESS VIEW  (what the caretaker dashboard summarises)
--    security_invoker keeps RLS in force: a caretaker only ever sees their own
--    patient's days.
-- ---------------------------------------------------------------------------
create or replace view public.daily_progress
with (security_invoker = true) as
select
  user_id,
  (created_at at time zone 'Asia/Kolkata')::date as day,
  count(*)                                       as sessions,
  round(avg(score))::int                         as avg_score,
  max(score)                                     as best_score,
  min(score)                                     as low_score,
  round(sum(coalesce(duration_seconds, 180)) / 60.0)::int as minutes
from public.game_scores
group by user_id, (created_at at time zone 'Asia/Kolkata')::date;

