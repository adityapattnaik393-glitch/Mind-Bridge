create policy "own scores select" on public.game_scores
  for select using (auth.uid() = user_id);

drop policy if exists "own scores insert" on public.game_scores;
create policy "own scores insert" on public.game_scores
  for insert with check (auth.uid() = user_id);

drop policy if exists "own alerts select" on public.cognitive_alerts;
create policy "own alerts select" on public.cognitive_alerts
  for select using (auth.uid() = user_id);

drop policy if exists "own alerts insert" on public.cognitive_alerts;
create policy "own alerts insert" on public.cognitive_alerts
  for insert with check (auth.uid() = user_id);

drop policy if exists "own alerts update" on public.cognitive_alerts;
create policy "own alerts update" on public.cognitive_alerts
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

